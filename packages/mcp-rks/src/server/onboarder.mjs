async function defaultCredentialResolver(args) {
  const { resolveInitCredential } = await import("../llm/claude-cli/subscription-status.mjs");
  // The real server env is passed as omitted, so resolveInitCredential's default path applies
  // (a boot-dotenv-copied opt-in is discounted, as at rks_governor_init); any other env is explicit.
  if (args && args.env === process.env) {
    const { env: _serverEnv, ...rest } = args;
    return resolveInitCredential(rest);
  }
  return resolveInitCredential(args);
}

/** Call the resolver; never throws. A throw or a non-object result becomes { error }. */
async function callResolver(resolver, projectRoot, env) {
  try {
    const res = await resolver({ projectRoot, env });
    if (!res || typeof res !== "object") return { error: "credential resolver returned no result" };
    return { res };
  } catch (err) {
    return { error: err?.message || String(err) };
  }
}

/** The blocker for `flow` under a gate, or null when admitted / no gate (gating off). */
function capabilityBlocker(gate, flow) {
  if (!gate) return null;
  if (gate.error) return "credential_unresolved";
  const cap = gate.capabilities?.[flow];
  if (cap === "admitted") return null;
  return (cap && typeof cap === "object" && cap.blocked) ? String(cap.blocked) : "not_admitted";
}

function blockedDispatchDisplay(header, governor, flow, blocker, gate) {
  // The recorded answer was api, and the FRESH gate observation still sees no credential: name the
  // missing key and the fix instead of the generic text (ARCH decision, onboarder-credential-step-edge-cases).
  if (gate && !gate.error && gate.choice === "api" && gate.credential === "none") {
    return `${header}

Not dispatching the ${governor}: you answered **api**, but no API key (\`ANTHROPIC_API_KEY\` or \`OPENAI_API_KEY\`) is visible to the MCP server, so the \`${flow}\` flow is blocked by \`${blocker}\`.

To fix it, set \`ANTHROPIC_API_KEY\` or \`OPENAI_API_KEY\` where the MCP server's environment is defined (the shell that launches it, or the project \`.env\` it loads at boot), then restart the MCP server — the server reads its environment at boot. Or answer the credential question again (\`/rks-onboard\`) with **subscription** or **neither** instead.`;
  }
  const why = gate?.error
    ? `the credential could not be determined (${gate.error})`
    : `the \`${flow}\` flow is blocked by \`${blocker}\` on this machine's credential`;
  return `${header}

Not dispatching the ${governor}: ${why}. Running it now would start a Governor the credential cannot carry.

To fix it, answer the credential question again (\`/rks-onboard\`, then give **api**, **subscription** or **neither**). The credential step shows what each flow needs and the exact fix.`;
}

function agentsYamlLines(agents) {
  return ["agents:", ...agents.flatMap((a) => [`  ${a}:`, "    backend: claude-cli"])];
}

function gitignoreListsEnv(projectRoot) {
  try {
    const text = fs.readFileSync(path.join(projectRoot, ".gitignore"), "utf8");
    return text.split(/\r?\n/).some((l) => [".env", "/.env", ".env*", "/.env*"].includes(l.trim()));
  } catch {
    return false;
  }
}

const OPT_IN_ANY_RE = new RegExp(`^\\s*(?:export\\s+)?${OPT_IN_KEY}\\s*=`, "m");
const OPT_IN_ON_RE = new RegExp(`^\\s*(?:export\\s+)?${OPT_IN_KEY}=1\\s*$`, "m");

/** Read back whether .env holds the opt-in line. Returns only a boolean; never the contents. */
function envShowsOptIn(envPath) {
  try { return OPT_IN_ON_RE.test(fs.readFileSync(envPath, "utf8")); } catch { return false; }
}

/**
 * Append the opt-in to the project .env. The entry never carries any .env value. A server-env
 * value the boot dotenv load copied in is not "defined in the server environment" (envOptInValue
 * returns undefined for it), so the project .env decides, as the hooks and the resolver read it.
 */
function writeEnvOptIn(projectRoot, env, envOptInValue = (e) => e[OPT_IN_KEY]) {
  const entry = { file: ".env", line: OPT_IN_LINE };
  const inEnv = env && typeof env === "object" ? envOptInValue(env) : undefined;
  if (inEnv !== undefined) {
    const isOn = inEnv === "1";
    return { ...entry, written: false, reason: isOn ? "env_already_on" : "env_defined_at_boot" };
  }
  if (!gitignoreListsEnv(projectRoot)) {
    return { ...entry, written: false, reason: "env_not_gitignored" };
  }
  const envPath = path.join(projectRoot, ".env");
  try {
    const exists = fs.existsSync(envPath);
    const prior = exists ? fs.readFileSync(envPath, "utf8") : "";
    if (OPT_IN_ANY_RE.test(prior)) {
      const shows = envShowsOptIn(envPath);
      return { ...entry, written: shows, action: "already_present", ...(shows ? {} : { reason: "env_has_other_value" }) };
    }
    const sep = prior.length > 0 && !prior.endsWith("\n") ? "\n" : "";
    fs.appendFileSync(envPath, `${sep}${OPT_IN_LINE}\n`, "utf8");
  } catch (err) {
    return { ...entry, written: false, reason: `write_failed: ${err?.code || err?.message || "error"}` };
  }
  const shows = envShowsOptIn(envPath);
  return { ...entry, written: shows, action: "appended", ...(shows ? {} : { reason: "read_back_failed" }) };
}

/** Create .rks/agents.yaml when absent; never modify an existing one. Reported from a read-back. */
function writeAgentsYaml(projectRoot, mods) {
  const agents = [...mods.FLOW_AGENTS["build-onrail"]];
  const entry = { file: AGENTS_YAML, agents };
  const yamlPath = path.join(projectRoot, ".rks", "agents.yaml");
  const unresolved = () => agents.filter((a) => mods.resolveAgentBackend(a, projectRoot) !== "claude-cli");
  let existed = false;
  try {
    existed = fs.statSync(yamlPath).isFile();
  } catch {
    existed = false;
  }
  if (existed) {
    const missing = unresolved();
    return missing.length === 0
      ? { ...entry, written: true, action: "already_configured" }
      : { ...entry, written: false, action: "left_unchanged", reason: "agents_yaml_exists", missing, lines: agentsYamlLines(missing) };
  }
  try {
    fs.mkdirSync(path.dirname(yamlPath), { recursive: true });
    fs.writeFileSync(yamlPath, `${agentsYamlLines(agents).join("\n")}\n`, { encoding: "utf8", flag: "wx" });
  } catch (err) {
    return { ...entry, written: false, reason: `write_failed: ${err?.code || err?.message || "error"}`, lines: agentsYamlLines(agents) };
  }
  const missing = unresolved();
  return missing.length === 0
    ? { ...entry, written: true, action: "created" }
    : { ...entry, written: false, action: "created", reason: "read_back_failed", missing };
}

function describeWrite(w) {
  if (w.file === ".env") {
    if (w.written && w.action === "appended") return `- \`.env\`: written — re-reading it shows \`${OPT_IN_LINE}\`.`;
    if (w.written) return `- \`.env\`: already holds \`${OPT_IN_LINE}\` (re-read); not appended again.`;
    switch (w.reason) {
      case "env_not_gitignored":
        return "- `.env`: **not written** — the project `.gitignore` has no `.env` line, so a credential file there could be committed. Add this exact line to `.gitignore`, then answer again:\n\n  ```\n  .env\n  ```";
      case "env_already_on":
        return `- \`.env\`: not written — \`${OPT_IN_KEY}\` is already on in the MCP server environment.`;
      case "env_defined_at_boot":
        return `- \`.env\`: **not written** — \`${OPT_IN_KEY}\` is already defined in the MCP server environment with a value other than 1. That value was set in the shell environment before MCP boot, so it is fixed for the server's lifetime and changing it needs an MCP restart (set it to 1 where the server's environment is defined, then restart).`;
      case "env_has_other_value":
        return `- \`.env\`: **not written** — it already has a \`${OPT_IN_KEY}\` line that is not \`${OPT_IN_LINE}\`. Change that line yourself to \`${OPT_IN_LINE}\`.`;
      default:
        return `- \`.env\`: **not written** (${w.reason}).`;
    }
  }
  if (w.written && w.action === "created") return `- \`${AGENTS_YAML}\`: written — created, and re-reading it resolves ${w.agents.map((a) => `\`${a}\``).join(", ")} to \`claude-cli\`.`;
  if (w.written) return `- \`${AGENTS_YAML}\`: already resolves ${w.agents.map((a) => `\`${a}\``).join(", ")} to \`claude-cli\` (re-read); left unchanged.`;
  if (w.reason === "agents_yaml_exists") {
    return `- \`${AGENTS_YAML}\`: **not written** — the file already exists and the onboarder never modifies it. Add these exact lines under its \`agents:\` key yourself:\n\n  \`\`\`yaml\n${w.lines.slice(1).map((l) => `  ${l}`).join("\n")}\n  \`\`\``;
  }
  return `- \`${AGENTS_YAML}\`: **not written** (${w.reason}).`;
}

function capabilitiesBlock(mods, capabilities, error) {
  const lines = [];
  if (error) {
    lines.push("**Flows:** none admitted — the credential could not be determined, so no flow is reported as admitted.");
  } else {
    lines.push("**Flows on this credential:**");
    for (const flow of mods.FLOWS) {
      const cap = capabilities?.[flow];
      if (cap === "admitted") lines.push(`  - \`${flow}\` — admitted`);
      else lines.push(`  - \`${flow}\` — blocked by ${cap && typeof cap === "object" && cap.blocked ? cap.blocked : "not_admitted"}`);
    }
  }
  lines.push("", "This capabilities map is report-only: it shows what the credential admits and changes no setting or gate.");
  return lines.join("\n");
}

const KEYLESS_DEMO_POINTER = "The keyless demo path works on any credential: `rks_rag_query` searches the local knowledge base with no API key, and grounded notes can be written under `keyless-notes.*`. Nothing was written.";

/** The 'neither' + detected-subscription sentence; the admitted flows come from the resolved map only. */
function subscriptionDetectedSentence(capabilities) {
  const admitted = Object.entries(capabilities || {}).filter(([, v]) => v === "admitted").map(([f]) => `\`${f}\``);
  const admits = admitted.length > 0 ? `it admits these flows: ${admitted.join(", ")}` : "it admits no flow";
  return `A subscription credential was detected (the subscription opt-in is on and no API key is visible); ${admits}. The other flows are listed below with their blockers.`;
}

async function handleCredentialStep(state, responses, { root, env, resolver }) {
  const rawChoice = typeof responses.credentialChoice === "string" ? responses.credentialChoice.trim().toLowerCase() : "";
  const choice = rawChoice === "api key" || rawChoice === "api-key" ? "api" : rawChoice;
  const stageLabel = state.currentStage || "welcome";
  if (!CREDENTIAL_CHOICES.includes(choice)) {
    return makePayload(stageLabel, state,
      "Credential step: answer with **api**, **subscription** or **neither** (an API key, a Claude subscription login, or no credential).",
      { ok: false, step: "credential", error: "invalid_credential_choice" });
  }
  const consent = responses.credentialConsent === "yes";
  const mods = await loadCredentialModules();
  const buildAgents = [...mods.FLOW_AGENTS["build-onrail"]];

  const writes = [];
  let resolved;
  if (choice === "subscription" && consent) {
    const pre = await callResolver(resolver, root, env);
    if (pre.res?.credential === "api") {
      resolved = pre;
    } else {
      writes.push(writeEnvOptIn(root, env, mods.serverEnvOptInValue));
      writes.push(writeAgentsYaml(root, mods));
      resolved = await callResolver(resolver, root, env);
    }
  } else {
    resolved = await callResolver(resolver, root, env);
  }

  const { res, error } = resolved;
  const credential = error ? null : (res.credential ?? null);
  const capabilities = error ? {} : (res.capabilities || {});
  const subscription = !error && res.subscription ? res.subscription : null;
  const credentialEntry = { choice, credential, ...(subscription ? { subscription } : {}), ...(error ? { error } : {}) };

  const out = [`**Credential check** — you answered **${choice}**.`];
  let caveat = null;
  let proposed = null;

  if (error) {
    out.push(`The credential could not be determined: ${error}. No flow is reported as admitted, and the tour will not dispatch a Governor until the credential step succeeds.`);
  } else if (credential === "api") {
    out.push(choice === "api"
      ? "An API key is present in the MCP server's environment, so every flow is admitted. Nothing was written, and the tour continues as usual."
      : `An API key is present in the MCP server's environment. An API key wins over the **${choice}** answer: every flow is admitted and nothing was written.`);
    if (choice === "neither") out.push(KEYLESS_DEMO_POINTER);
  } else if (choice === "api") {
    out.push("No API key (`ANTHROPIC_API_KEY` or `OPENAI_API_KEY`) is visible to the MCP server. Set one where the MCP server's environment is defined and restart the MCP server, or answer **subscription** or **neither** instead. Nothing was written.");
  } else if (choice === "neither" && credential === "subscription") {
    out.push(subscriptionDetectedSentence(capabilities));
    out.push(KEYLESS_DEMO_POINTER);
  } else if (choice === "neither") {
    out.push("No credential is set up. You can still use the keyless demo path: `rks_rag_query` searches the local knowledge base with no API key, and grounded notes can be written under `keyless-notes.*`. Generation flows (Governors, plan, build, ship) stay blocked. Nothing was written.");
  }

  if (!error && credential === "subscription" && subscription) {
    out.push(`**Subscription probe:** ready: \`${subscription.ready === true}\`, reason: \`${subscription.reason ?? "none"}\`.`);
    if (subscription.ready !== true) {
      out.push(`Fix: ${mods.subscriptionFixHint({ probeReason: subscription.reason || null })}.`);
    }
  }

  if (choice === "subscription" && !error && credential !== "api") {
    out.push(`The subscription path needs Claude Code CLI ${mods.MIN_CLAUDE_VERSION} or later, logged in with a claude.ai account. Check with \`claude auth status\`; log in with \`claude /login\`.`);
    if (writes.length > 0) {
      out.push("**Writes (each reported from a read-back):**", writes.map(describeWrite).join("\n"));
    } else if (credential !== "subscription") {
      const yamlLines = agentsYamlLines(buildAgents);
      proposed = { env: OPT_IN_LINE, agentsYaml: yamlLines };
      out.push(`To use the subscription, two opt-ins are needed. With your consent the onboarder makes these writes itself, inside this project only; nothing has been written yet.

1. Append this exact line to the project \`.env\` (only if \`.gitignore\` lists \`.env\`; no other \`.env\` value is read out or shown):

   \`\`\`
   ${OPT_IN_LINE}
   \`\`\`

2. Create \`${AGENTS_YAML}\` with these exact lines (only if the file does not exist; an existing file is never modified, and you get the lines to add instead):

   \`\`\`yaml
${yamlLines.map((l) => `   ${l}`).join("\n")}
   \`\`\`

Do you agree to these writes? Reply **yes** to let the onboarder make them, or **no** to skip.`);
    }
    out.push(OPT_IN_TIMING);
  }

  out.push(capabilitiesBlock(mods, capabilities, error));

  if (!error && credential === "subscription" && capabilities["build-onrail"] === "admitted" && !(env && env.ROUTEKIT_LLM_MODEL)) {
    caveat = "ROUTEKIT_LLM_MODEL is unset: on-rail Build on the subscription also needs a planner model, and the capabilities map does not check it.";
    out.push("**Caveat:** `ROUTEKIT_LLM_MODEL` is not set. On-rail Build on the subscription also needs it (there is no default model), and the capabilities map does not check it, so `build-onrail` can read admitted while the planner has no model. Model choice is yours: the onboarder never writes `ROUTEKIT_LLM_MODEL`.");
  }

  out.push("Type **yes** (or any response) to continue the tour.");

  state.credential = { choice, credential, recordedAt: Date.now(), ...(error ? { error } : {}) };
  let saved = state;
  try { saved = saveOnboarderState(root, state); } catch { /* state write best-effort (e.g. .rks is not a directory) */ }

  return makePayload(stageLabel, saved, out.join("\n\n"), {
    step: "credential",
    credential: credentialEntry,
    capabilities,
    writes,
    ...(proposed ? { proposed } : {}),
    ...(caveat ? { caveat } : {}),
  });
}

// ─── Entry point ──────────────────────────────────────────────────────────────

function selectStage(state, explicitStage) {
  if (explicitStage) return explicitStage;
  const completed = new Set(state.completedStages || []);
  for (const stage of STAGES) {
    if (!completed.has(stage)) return stage;
  }
  return "next_steps";
}

export async function runOnboarder({
  projectId,
  projectRoot,
  stage,
  responses,
  skipTour,
  skipStage,
  bounce,
  resume,
  reset,
  credentialResolver = defaultCredentialResolver,
  env = process.env,
} = {}) {
  const root = projectRoot || process.cwd();
  const resolver = typeof credentialResolver === "function" ? credentialResolver : defaultCredentialResolver;
  let state = getOnboarderState(root);
  if (projectId) state.projectId = projectId;

  // Abandoned inference: emit once when a prior session is stale (> 24h) and never completed
  const TWENTY_FOUR_HOURS = 24 * 60 * 60 * 1000;
  if (
    state.startedAt &&
    !state.completedAt &&
    !state.abandonedEmitted &&
    Date.now() - state.lastTouchedAt > TWENTY_FOUR_HOURS
  ) {
    emit(root, "onboarder.abandoned", {
      stuckAt: state.currentStage,
      lastTouchedAt: state.lastTouchedAt,
    });
    state.abandonedEmitted = true;
    saveOnboarderState(root, state);
  }

  if (reset) {
    const now = Date.now();
    state = {
      version: 1,
      startedAt: now,
      lastTouchedAt: now,
      completedStages: [],
      currentStage: "welcome",
      projectId: projectId || state.projectId,
    };
    saveOnboarderState(root, state);
  }

  // skipTour: mark all stages except next_steps as skipped, jump to next_steps
  if (skipTour) {
    const skippable = STAGES.filter(s => s !== "next_steps");
    for (const s of skippable) {
      if (!state.completedStages.includes(s)) {
        emit(root, "onboarder.stage.skipped", { stage: s, reason: "dismissed" });
      }
    }
    state.completedStages = skippable;
    state.currentStage = "next_steps";
    const proj = readProjectJson(root);
    proj.onboarder = {
      ...(proj.onboarder || {}),
      completedAt: Date.now(),
      completedVersion: "skipped-as-power-user",
    };
    writeProjectJson(root, proj);
    const saved = saveOnboarderState(root, state);
    const result = handleNextSteps(saved, {}, root);
    result.state = saved;
    return result;
  }

  // Credential step: rides on responses, adds no stage, does not advance completedStages.
  if (responses && typeof responses === "object" && responses.credentialChoice !== undefined) {
    return handleCredentialStep(state, responses, { root, env, resolver });
  }

  // Dispatch gating: only once a credential has been recorded; with none recorded, gating is off
  // and the resolver is never called.
  const gateFor = async (stageName) => {
    if (!state.credential) return null;
    if (stageName !== "first_story" && stageName !== "first_build") return null;
    const { res, error } = await callResolver(resolver, root, env);
    if (error) return { error };
    return { capabilities: res.capabilities || {}, credential: res.credential ?? null, choice: state.credential.choice ?? null };
  };

  const targetStage = selectStage(state, stage);

  // skipStage: skip current stage, advance to next
  if (skipStage) {
    emit(root, "onboarder.stage.skipped", { stage: targetStage, reason: "user-skip" });
    if (!state.completedStages.includes(targetStage)) {
      state.completedStages.push(targetStage);
    }
    state.currentStage = targetStage;
    const saved = saveOnboarderState(root, state);
    const nextStage = selectStage(saved, null);
    const handler = HANDLERS[nextStage];
    if (!handler) return { ok: false, error: `Unknown stage: ${nextStage}` };
    const result = handler(saved, { responses, bounce, credentialGate: await gateFor(nextStage) }, root);
    saved.currentStage = nextStage;
    result.state = saveOnboarderState(root, saved);
    return result;
  }

  const handler = HANDLERS[targetStage];
  if (!handler) {
    return { ok: false, error: `Unknown stage: ${targetStage}` };
  }

  const result = handler(state, { responses, bounce, credentialGate: await gateFor(targetStage) }, root);
  state.currentStage = targetStage;
  const saved = saveOnboarderState(root, state);
  result.state = saved;
  return result;
}
