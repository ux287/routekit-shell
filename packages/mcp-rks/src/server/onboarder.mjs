// Not a stage: STAGES is unchanged. It runs when responses.credentialChoice is present, returns its
// own payload and leaves completedStages alone. The credential modules are loaded by dynamic import
// inside this path only, so importers of onboarder.mjs gain no import-time dependency.

export const CREDENTIAL_CHOICES = Object.freeze(["api", "subscription", "neither"]);
const OPT_IN_KEY = "RKS_SUBSCRIPTION_CREDENTIAL";
const OPT_IN_LINE = `${OPT_IN_KEY}=1`;
const AGENTS_YAML = ".rks/agents.yaml";
const OPT_IN_TIMING =
  "Timing: the project `.env` opt-in is read fresh at each Governor start, so it takes effect at the next Governor start with no MCP restart (a copy the server's boot-time `.env` load picked up is ignored for this key). Only a `RKS_SUBSCRIPTION_CREDENTIAL` value set in the shell environment before MCP boot is fixed for the server's lifetime; changing that one needs an MCP restart.";

